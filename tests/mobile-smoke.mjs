import { launchBrowser } from './browser-runtime.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await launchBrowser();
const context = await browser.newContext({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
const page = await context.newPage(); page.setDefaultTimeout(120000);
const errors = [], failedRequests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('response', r => { if (r.status() >= 400) failedRequests.push(r.url() + ': ' + r.status()); });
await page.addInitScript(() => localStorage.setItem('blackline-save-v1', JSON.stringify({ settings: { quality: 'Saver', shadows: false, post: false } })));
await page.goto(process.env.TEST_URL || 'http://localhost:5173/', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.blackline?.ready);
await fs.mkdir('test-results', { recursive: true });
await page.screenshot({ path: 'test-results/menu-mobile-landscape.png' });
await page.locator('[data-mode="training"]').tap(); await page.locator('[data-action="deploy"]').tap();
await page.waitForFunction(() => window.blackline.snapshot().state === 'playing');
const cdp = await context.newCDPSession(page);
const rect = selector => page.locator(selector).boundingBox();
const joystick = await rect('#joystick'), fire = await rect('.touch-fire');
const move = { id: 1, x: joystick.x + joystick.width / 2, y: joystick.y + joystick.height / 2 };
const look = { id: 2, x: 440, y: 180 };
const trigger = { id: 3, x: fire.x + fire.width / 2, y: fire.y + fire.height / 2 };
const touch = (type, points) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: points });
await touch('touchStart', [move]);
move.x += 18; move.y -= 24; await touch('touchMove', [move]);
await touch('touchStart', [move, look]);
look.x += 30; look.y -= 8; await touch('touchMove', [move, look]);
await touch('touchStart', [move, look, trigger]);
await page.waitForFunction(() => { const s = window.blackline.snapshot(); return s.pointers === 3 && s.firing && s.ammo < 30; });
const concurrent = await page.evaluate(() => window.blackline.snapshot());
assert.equal(concurrent.pointers, 3); assert.ok(concurrent.moving.x > 0 && concurrent.moving.y > 0); assert.ok(concurrent.ammo < 30);
console.log('MULTI-TOUCH PASS', concurrent);
await touch('touchEnd', []);
await page.waitForFunction(() => window.blackline.snapshot().pointers === 0);
assert.equal((await page.evaluate(() => window.blackline.snapshot())).firing, false);
await page.locator('.touch-ads').tap(); assert.equal((await page.evaluate(() => window.blackline.snapshot())).aiming, true);
await page.locator('.touch-crouch').tap(); await page.locator('.touch-reload').tap();
await page.screenshot({ path: 'test-results/training-mobile.png' });
await page.locator('[data-combat="armory"]').tap();
await page.waitForFunction(() => window.blackline.snapshot().state === 'armory');
await page.locator('[data-category="Marksman"]').tap(); await page.locator('[data-weapon="awp"]').tap(); await page.locator('#equip-button').tap();
assert.equal((await page.evaluate(() => window.blackline.snapshot())).weapon, 'awp');
await page.locator('[data-attachment="laser"]').tap();
await page.locator('[data-action="close-panel"]').tap();
await page.waitForFunction(() => window.blackline.snapshot().state === 'playing');
await page.locator('[data-action="pause"]').tap(); await page.locator('#pause [data-action="exit"]').tap();
await page.locator('[data-mode="deployment"]').tap(); await page.locator('[data-action="deploy"]').tap();
await page.waitForFunction(() => { const s = window.blackline.snapshot(); return s.state === 'playing' && s.wave === 1 && s.enemies === 3; });
await page.waitForTimeout(2000); await page.screenshot({ path: 'test-results/deployment-mobile.png' });
console.log('DEPLOYMENT', await page.evaluate(() => window.blackline.snapshot()));
await page.locator('[data-action="pause"]').tap(); await page.locator('#pause [data-action="exit"]').tap();
await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(1000);
await page.screenshot({ path: 'test-results/menu-mobile-portrait.png' });
const deploy = await rect('[data-action="deploy"]'); assert.ok(deploy.y + deploy.height < 844);
console.log('ERRORS', errors); console.log('FAILED HTTP RESPONSES', failedRequests);
assert.deepEqual(errors, []); assert.deepEqual(failedRequests, []);
await browser.close();
