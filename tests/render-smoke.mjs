import { launchBrowser } from './browser-runtime.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await launchBrowser();
const page = await browser.newPage({ viewport: { width: 640, height: 480 } }); page.setDefaultTimeout(120000);
const errors = [], missing = [];
page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('response', r => { if (r.status() >= 400) missing.push(r.url()); });
await page.goto(process.env.TEST_URL || 'http://localhost:5173/', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.blackline?.ready);
console.log('DEFAULT BALANCED PIPELINE STARTED', await page.evaluate(() => window.blackline.snapshot()));
await fs.mkdir('test-results', { recursive: true });
await page.screenshot({ path: 'test-results/default-balanced.png', timeout: 120000 });
const press = selector => page.locator(selector).first().dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await press('[data-action="settings"]'); await press('#shadow-toggle'); await press('[data-quality="Ultra"]');
await page.waitForTimeout(600); await press('[data-quality="Saver"]'); await press('#post-toggle'); await press('#post-toggle'); await press('#shadow-toggle');
await page.waitForTimeout(800); await press('#settings [data-action="close-modal"]');
console.log('DYNAMIC SETTINGS PASSED'); console.log('ERRORS', errors); console.log('MISSING ASSETS', missing);
assert.deepEqual(errors, []); assert.deepEqual(missing, []);
await browser.close();
