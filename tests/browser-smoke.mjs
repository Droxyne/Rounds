import { launchBrowser } from './browser-runtime.mjs';
import fs from 'node:fs/promises';
const browser = await launchBrowser();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.setDefaultTimeout(120000);
await page.addInitScript(() => localStorage.setItem('blackline-save-v1', JSON.stringify({ settings: { quality: 'Saver', shadows: false } })));
const errors = [], warnings = [];
page.on('pageerror', e => { errors.push(e.message); console.error('PAGE ERROR:', e.message); });
page.on('console', m => { if (m.type() === 'error') { errors.push(m.text()); console.error('CONSOLE ERROR:', m.text()); } else if (m.type() === 'warning') warnings.push(m.text()); });
page.on('requestfailed', r => { errors.push(r.url() + ' ' + r.failure()?.errorText); });
await page.goto(process.env.TEST_URL || 'http://localhost:5173/', { waitUntil: 'networkidle', timeout: 120000 });
await page.waitForFunction(() => window.blackline?.ready, { timeout: 120000 });
await page.waitForTimeout(2500);
await fs.mkdir('test-results', { recursive: true });
await page.screenshot({ path: 'test-results/menu-desktop.png' });
console.log('MENU', await page.evaluate(() => window.blackline.snapshot()));
await page.locator('[data-action="armory"]').first().dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.waitForTimeout(1500);
await page.screenshot({ path: 'test-results/armory-desktop.png' });
console.log('ARMORY', await page.evaluate(() => window.blackline.snapshot()));
await page.locator('[data-action="close-panel"]').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.locator('[data-mode="training"]').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.locator('[data-action="deploy"]').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.waitForTimeout(2500);
await page.screenshot({ path: 'test-results/training-desktop.png' });
console.log('TRAINING', await page.evaluate(() => window.blackline.snapshot()));
await page.keyboard.down('KeyW'); await page.waitForTimeout(700); await page.keyboard.up('KeyW');
await page.keyboard.press('KeyF'); await page.keyboard.press('KeyG');
await page.waitForTimeout(3000);
console.log('MOVED', await page.evaluate(() => window.blackline.snapshot()));
await page.locator('[data-action="pause"]').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.locator('#pause [data-action="settings"]').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.locator('[data-quality="Saver"]').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.locator('#post-toggle').dispatchEvent('pointerdown', { pointerId: 1, pointerType: 'mouse', bubbles: true });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'test-results/settings.png' });
console.log('ERRORS', JSON.stringify(errors)); console.log('WARNINGS', JSON.stringify([...new Set(warnings)].slice(0, 10)));
await browser.close();
if (errors.length) process.exit(1);
